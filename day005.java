package src;

public class day005 {
    public static void main(String[] args) {
        // float(single precision) Tipe data desimal dengan ukuran memori 32-bit (4
        // byte) dengan tingkat ketelitiannya hingga 6-7 digit di belakang koma
        float rateMuka = 0.1f;
        // double (Double Precision) Tipe data desimal dengan ukuran memori 64-bit (8
        // byte) dengan tingkat ketelitian ganda hingga 15-17 digit di belakang koma
        double isiRekening = 230300.5;

        System.out.println("Rating muka \t:" + rateMuka);
        System.out.println("Rating muka \t:" + isiRekening);
    }

}
